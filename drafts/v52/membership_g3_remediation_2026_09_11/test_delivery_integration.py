    def test_strict_output_negatives_before_open(self):
        mutations = [
            lambda r: r["estimates"].update({CANARY: CANARY}),
            lambda r: r["estimates"].update(n_question_slots=True),
            lambda r: r["estimates"].update(per_seed_G_pp=[0.]),
            lambda r: r["bootstrap_configuration"].update(replicates=1),
            lambda r: r["bootstrap_configuration"].update(seed=True),
            lambda r: r["uncertainty"]["intervals"]["G_bar_pp"].update(lo=1., hi=-1.),
            lambda r: r["uncertainty"]["intervals"]["G_bar_pp"].update(spans_zero="yes"),
            lambda r: r["uncertainty"].update(interpretation=CANARY),
        ]
        for mutate in mutations:
            r = copy.deepcopy(self.result)
            mutate(r)
            rebind(r, "result_sha256")
            target = self.root / "invalid-output.json"
            original = Path.open
            modes = []
            def read_only(path, mode="r", *args, **kwargs):
                modes.append(mode)
                return original(path, mode, *args, **kwargs)
            with mock.patch.object(Path, "open", new=read_only):
                self.refusal(lambda: bridge.write_synthetic_result(target, r))
            self.assertTrue(all("x" not in mode and "w" not in mode for mode in modes))
            self.assertFalse(target.exists())
        r = copy.deepcopy(self.result)
        r["estimates"]["G_bar_pp"] = float("nan")
        self.refusal(lambda: bridge.write_synthetic_result(self.root / "nan.json", r))
        self.assertFalse((self.root / "nan.json").exists())

    def test_exclusive_create_race_and_unchanged_sentinel(self):
        target = self.root / "existing.json"
        sentinel = b"unchanged sentinel bytes\x00\xff"
        target.write_bytes(sentinel)
        self.refusal(lambda: bridge.write_synthetic_result(target, self.result), "E-G3-I98")
        self.assertEqual(target.read_bytes(), sentinel)
        race = self.root / "race.json"
        original = Path.open
        def racing_open(path, mode="r", *args, **kwargs):
            if path == race and mode == "xb":
                with original(path, "xb") as stream:
                    stream.write(sentinel)
            return original(path, mode, *args, **kwargs)
        with mock.patch.object(Path, "open", new=racing_open):
            self.refusal(lambda: bridge.write_synthetic_result(race, self.result), "E-G3-I98")
        self.assertEqual(race.read_bytes(), sentinel)

