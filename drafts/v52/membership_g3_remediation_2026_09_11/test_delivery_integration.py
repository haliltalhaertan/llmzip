def rebind(value, field="binding_sha256"):
    value[field] = bridge._digest({k: v for k, v in value.items() if k != field})


def surface(exc):
    parts, pending, seen = [], [exc], set()
    while pending:
        node = pending.pop()
        if id(node) in seen:
            continue
        seen.add(id(node))
        parts.extend((str(node), repr(node), "".join(traceback.format_exception(node))))
        pending.extend(x for x in (node.__cause__, node.__context__) if x is not None)
    return "\n".join(parts)


class DeliveryIntegration(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.tmp = tempfile.TemporaryDirectory(prefix="delivery_integration_", dir=HERE)
        cls.root = Path(cls.tmp.name)
        n = 110
        # All generated units are gold, so the independent native anchor is exactly 3/n.
        messages = [{"dia_id": f"D1:{j}", "speaker": "Fixture",
                     "text": f"synthetic archive token{j} topic{j % 13} item{j * 17} detail{j % 7}"}
                    for j in range(n)]
        evidence = [x["dia_id"] for x in messages]
        raw = json.dumps([{"conversation": {"session_1": messages}, "qa": [
            {"question": "synthetic topic3 item34 query", "evidence": evidence},
            {"question": "synthetic topic8 item51 query", "evidence": evidence}]}]).encode()
        cls.source_bytes = raw
        cls.path = cls.root / "synthetic_fixture.json"
        cls.path.write_bytes(raw)
        sha = hashlib.sha256(raw).hexdigest()
        cls.mapping = {"provenance": bridge.SYNTHETIC, "source_id": "synthetic_fixture",
            "source_sha256": sha, "benchmark": runner.LOCOMO, "n_questions": 2,
            "expected_cluster_ids": ["locomo_conv_0"],
            "expected_question_to_cluster": {"locomo_0_qa0": "locomo_conv_0", "locomo_0_qa1": "locomo_conv_0"}}
        cls.identity = {"source_file": cls.path.name, "source_sha256": sha, "source_bytes": len(raw)}

        def fixture_bytes(path, benchmark, *, enabled=None):
            assert Path(path) == cls.path and benchmark == runner.LOCOMO and enabled is None
            assert Path(path).read_bytes() == raw
            return dict(cls.identity)

        def fixture_mapping(mapping, benchmark):
            assert mapping == cls.mapping and benchmark == runner.LOCOMO
            assert "_accepted_manifest_sha256" not in mapping

        with mock.patch.object(ingest, "verify_source_bytes", side_effect=fixture_bytes), \
             mock.patch.object(ingest, "_check_accepted_mapping", side_effect=fixture_mapping), \
             mock.patch.object(runner.core, "require_real_data_authorization", side_effect=AssertionError("auth must not be called")):
            cls.ingested = ingest.ingest_locomo(cls.path, copy.deepcopy(cls.mapping))
        cls.prepared = pipeline.assemble_in_memory(cls.ingested, {q: float(3 / n) for q in cls.ingested["cohort_ids"]})
        cls.envelope = bridge.prepare_synthetic_envelope(cls.ingested, cls.prepared, raw)
        cls.result = bridge.compute_synthetic_result(cls.envelope)

    @classmethod
    def tearDownClass(cls):
        cls.tmp.cleanup()

    def refusal(self, call, code=None):
        with self.assertRaises(bridge.IntegrationError) as got:
            call()
        if code is not None:
            self.assertEqual(str(got.exception), code)
        self.assertNotIn(CANARY, surface(got.exception))
        self.assertIsNone(got.exception.__context__)
        self.assertIsNone(got.exception.__cause__)

    def test_real_fixture_ingress_assemble_bootstrap_output(self):
        self.assertEqual(len(self.prepared["records"]), 120)
        self.assertEqual(self.result["provenance"], bridge.SYNTHETIC)
        self.assertEqual(self.result["bootstrap_configuration"]["replicates"], 10000)
        self.assertEqual(self.result["bootstrap_configuration"]["seed"], 52001107)
        self.assertEqual(self.result["estimates"]["n_question_slots"], 2)
        self.assertEqual(self.result["preparation"]["source_identity"]["source_sha256"], hashlib.sha256(self.source_bytes).hexdigest())
        self.assertEqual(self.result["preparation"]["code_hashes"], bridge._code_hashes())
        self.assertNotIn("_accepted_manifest_sha256", json.dumps(self.result))
        self.assertNotIn("frozen_before_any_result", json.dumps(self.result))
        out = self.root / "result.json"
        bridge.write_synthetic_result(out, self.result)
        self.assertEqual(json.loads(out.read_bytes()), self.result)

    def test_shared_cluster_delegation_and_nonzero_point_estimates(self):
        e = copy.deepcopy(self.envelope)
        scores = {"NATIVE": .2, "SCALED_NATIVE": .2, "B32_FRESH": .6,
                  "RANDOM32_FRESH": .2, "SCALED_B32": .4, "SCALED_RANDOM32": .3}
        for row in e["records"]:
            row["fractional_R3"] = scores[row["arm"]]
        rebind(e)
        r = bridge.compute_synthetic_result(e, scheme="cluster")
        self.assertEqual(r["bootstrap_configuration"]["seed"], 52001207)
        self.assertEqual(r["uncertainty"]["replicates"], 10000)
        for key, expected in zip(bridge.SCALARS, (40., 10., -30.)):
            self.assertAlmostEqual(r["estimates"][key], expected)
            self.assertAlmostEqual(r["uncertainty"]["intervals"][key]["lo"], expected)
            self.assertAlmostEqual(r["uncertainty"]["intervals"][key]["hi"], expected)

    def test_malformed_records_refused_before_numerics(self):
        variants = []
        for field, values in {"question_id": [CANARY, 1], "rotation_seed": [60001.9, "60001", True],
                              "arm": [CANARY, None], "fractional_R3": [True, "bad", -1., 2., float("nan"), float("inf")]}.items():
            for value in values:
                e = copy.deepcopy(self.envelope)
                e["records"][0][field] = value
                variants.append(e)
        for kind in ("missing", "extra", "duplicate", "empty", "nondict"):
            e = copy.deepcopy(self.envelope)
            if kind == "missing":
                del e["records"][0]["fractional_R3"]
            elif kind == "extra":
                e["records"][0][CANARY] = CANARY
            elif kind == "duplicate":
                e["records"][1] = copy.deepcopy(e["records"][0])
            elif kind == "empty":
                e["records"] = []
            else:
                e["records"][0] = CANARY
            variants.append(e)
        with mock.patch.object(runner, "compute_synthetic_results") as compute:
            for e in variants:
                with self.subTest(record=e["records"][:1]):
                    self.refusal(lambda: bridge.compute_synthetic_result(e), "E-G3-I04")
            compute.assert_not_called()

